/* one line of text → lit dots (c, r) in a 7-row strip; 1 blank column between glyphs */
export function lineDots(segments) {
  const dots = []
  let c = 0
  for (const { text, color } of segments) {
    for (const ch of text.toUpperCase()) {
      const rows = (FONT5[ch] || FONT5[' ']).split('|')
      rows.forEach((row, r) => [...row].forEach((v, x) => { if (v === '#') dots.push({ c: c + x, r, color }) }))
      c += 6
    }
  }
  return { cols: c, dots }
}
